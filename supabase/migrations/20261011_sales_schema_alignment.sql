-- Sales schema alignment for the enterprise Sales workflow.
-- This migration is intentionally NOT applied automatically by this change.
-- It refuses to change ID types if any sale already exists, because old numeric
-- references must be mapped to their UUID counterparts rather than discarded.

do $$
begin
  if exists (select 1 from public.sales limit 1) then
    raise exception 'Sales schema alignment stopped: sales contains rows. Map existing numeric team/version references to UUIDs before changing column types.';
  end if;
end $$;

-- These columns currently use numeric types while their target tables use UUID IDs.
alter table public.sales
  alter column team_id type uuid using null::uuid,
  alter column team_structure_version_id type uuid using null::uuid,
  alter column team_split_version_id type uuid using null::uuid;

-- The create-sale function stores this reference; the column was missing from sales.
alter table public.sales
  add column if not exists receipt_reference text;

-- Preserve multiple people in the same role by storing their position explicitly.
alter table public.team_assignments
  add column if not exists employee_position integer not null default 1;

alter table public.team_assignments
  drop constraint if exists team_assignments_employee_position_check;

alter table public.team_assignments
  add constraint team_assignments_employee_position_check
  check (employee_position >= 1);

-- Add only the intended FK constraints; drop/recreate these named constraints so
-- this migration can be safely re-run in a development database.
alter table public.sales
  drop constraint if exists sales_team_id_fkey,
  drop constraint if exists sales_team_structure_version_id_fkey,
  drop constraint if exists sales_team_split_version_id_fkey;

alter table public.sales
  add constraint sales_team_id_fkey
    foreign key (team_id) references public.teams(id),
  add constraint sales_team_structure_version_id_fkey
    foreign key (team_structure_version_id) references public.team_structures(id),
  add constraint sales_team_split_version_id_fkey
    foreign key (team_split_version_id) references public.team_split_versions(id);

-- Used by create-sale and the sales review screens to preserve the approved
-- employee-level commission allocation for each submitted sale.
create table if not exists public.sale_commission_allocations (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  employee_id uuid not null references public.profiles(id),
  role_code text not null check (role_code in ('lead','assistant','driver')),
  employee_position integer not null default 1 check (employee_position >= 1),
  split_percentage numeric(7,4) not null check (split_percentage >= 0 and split_percentage <= 100),
  allocated_commission numeric(14,2) not null default 0 check (allocated_commission >= 0),
  team_assignment_id uuid references public.team_assignments(id),
  team_split_version_id uuid references public.team_split_versions(id),
  created_at timestamptz not null default now(),
  unique (sale_id, employee_id, role_code, employee_position)
);

create index if not exists sale_commission_allocations_sale_id_idx
  on public.sale_commission_allocations(sale_id);
create index if not exists sale_commission_allocations_employee_id_idx
  on public.sale_commission_allocations(employee_id);

alter table public.sale_commission_allocations enable row level security;

drop policy if exists sale_commission_allocations_select_scoped
  on public.sale_commission_allocations;

create policy sale_commission_allocations_select_scoped
on public.sale_commission_allocations
for select to authenticated
using (
  exists (
    select 1
    from public.sales s
    join public.profiles p on p.id = auth.uid()
    where s.id = sale_commission_allocations.sale_id
      and (
        p.role = 'super_admin'
        or (
          p.organization_id = s.organization_id
          and (
            p.role = 'admin'
            or (p.role = 'branch_admin' and p.branch_id = s.branch_id)
            or p.id in (s.submitted_by, s.lead_id, s.assistant_id, s.driver_id)
            or private.has_management_permission('sales.review')
            or private.has_management_permission('commission.view')
            or private.has_management_permission('earnings.view')
            or private.has_management_permission('performance.view')
            or private.has_management_permission('reports.export')
          )
        )
      )
  )
);
